// Bundles the service together with the SMM TestBench engine sources into dist/.
//   node build.mjs               build dist/smm-automation-service.mjs
//   node build.mjs --paths-only  only write tsconfig.testbench.json (for tsc)
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { aliasResolver, assertPinned, locateTestbench, withExtension } from './testbench.mjs'

const tb = locateTestbench()
assertPinned(tb)

const toPosix = (p) => p.replaceAll('\\', '/')
writeFileSync(
  'tsconfig.testbench.json',
  JSON.stringify(
    {
      $comment: 'Generated by build.mjs from SMM_TESTBENCH_DIR. Do not edit.',
      compilerOptions: {
        paths: {
          '@tb/sim/*': [toPosix(join(tb.simulator, 'src/*'))],
          '@tb/hw/*': [toPosix(join(tb.hwsim, 'src/*'))],
          // The two apps' shared folders do not overlap, so tsc can try one after the other.
          '@shared/*': [toPosix(join(tb.simulator, 'src/shared/*')), toPosix(join(tb.hwsim, 'src/shared/*'))],
        },
      },
    },
    null,
    2,
  ),
)
if (process.argv.includes('--paths-only')) process.exit(0)

const resolveAlias = aliasResolver(tb)
const testbenchAliases = {
  name: 'smm-testbench-aliases',
  setup(b) {
    b.onResolve({ filter: /^@(tb\/(sim|hw)|shared)\// }, (args) => {
      const target = resolveAlias(args.path, args.importer)
      return target ? { path: withExtension(target) } : undefined
    })
  },
}

const info = {
  dir: tb.dir,
  commit: tb.commit,
  pinnedCommit: tb.pinnedCommit,
  pinned: tb.pinned,
  dirty: tb.dirty,
  simulatorVersion: tb.simulatorVersion,
  hwsimVersion: tb.hwsimVersion,
  builtAt: new Date().toISOString(),
}

await build({
  entryPoints: ['src/main.ts'],
  outfile: 'dist/smm-automation-service.mjs',
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  sourcemap: true,
  logLevel: 'warning',
  plugins: [testbenchAliases],
  define: { __TESTBENCH__: JSON.stringify(info) },
  // CommonJS dependencies (mqtt, ajv, aedes) call require() for Node built-ins.
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
})
console.log(`Built dist/smm-automation-service.mjs from SMM TestBench ${tb.commit?.slice(0, 7)}${tb.dirty ? ' (dirty)' : ''} at ${tb.dir}`)
